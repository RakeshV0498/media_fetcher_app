export function Skeletons({ n = 3 }: { n?: number }) {
  return <div className="grid">{Array.from({ length: n }, (_, i) => <div key={i} className="card skeleton" />)}</div>;
}

export function Poster({ url, title }: { url: string | null; title: string }) {
  const hue = [...title].reduce((a, c) => (a * 31 + c.charCodeAt(0)) % 360, 7);
  const initials = title.split(/\s+/).filter(Boolean).slice(0, 2).map((w) => w[0]).join("").toUpperCase();
  if (url) return <img className="poster" src={url} alt="" loading="lazy" />;
  return (
    <div className="poster fallback" style={{ background: `linear-gradient(145deg, hsl(${hue} 55% 38%), hsl(${(hue + 40) % 360} 60% 22%))` }}>
      <span>{initials || "?"}</span>
    </div>
  );
}

